\set ON_ERROR_STOP on
BEGIN;
-- IDs da carga são estáveis; novos IDs gerados começam em 100.
DO $$
BEGIN
  IF to_regclass('public.cursos') IS NULL THEN
    CREATE TABLE cursos (
      id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
      nome_curso text NOT NULL
    );
  END IF;
  IF to_regclass('public.alunos') IS NULL THEN
    CREATE TABLE alunos (
      id integer GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
      nome text NOT NULL,
      email text NOT NULL,
      curso_id integer NOT NULL REFERENCES cursos(id)
    );
  END IF;
END $$;
-- Reexecução só aceita o schema esperado; não esconde tabelas incompatíveis.
DO $$
DECLARE actual text[];
BEGIN
  SELECT array_agg(attname || ':' || format_type(atttypid, atttypmod) || ':' ||
    attnotnull::text || ':' || attidentity::text ORDER BY attnum)
    INTO actual FROM pg_attribute WHERE attrelid = 'cursos'::regclass
    AND attnum > 0 AND NOT attisdropped;
  IF actual IS DISTINCT FROM ARRAY['id:integer:true:d','nome_curso:text:true:'] THEN
    RAISE EXCEPTION 'Schema incompatível em cursos; use um banco dedicado vazio';
  END IF;
  SELECT array_agg(attname || ':' || format_type(atttypid, atttypmod) || ':' ||
    attnotnull::text || ':' || attidentity::text ORDER BY attnum)
    INTO actual FROM pg_attribute WHERE attrelid = 'alunos'::regclass
    AND attnum > 0 AND NOT attisdropped;
  IF actual IS DISTINCT FROM ARRAY['id:integer:true:d','nome:text:true:',
      'email:text:true:','curso_id:integer:true:'] THEN
    RAISE EXCEPTION 'Schema incompatível em alunos; use um banco dedicado vazio';
  END IF;
  IF (SELECT array_agg(pg_get_constraintdef(oid) ORDER BY contype)
      FROM pg_constraint WHERE conrelid = 'cursos'::regclass)
      IS DISTINCT FROM ARRAY['PRIMARY KEY (id)'] OR
     (SELECT array_agg(pg_get_constraintdef(oid) ORDER BY contype)
      FROM pg_constraint WHERE conrelid = 'alunos'::regclass)
      IS DISTINCT FROM ARRAY['FOREIGN KEY (curso_id) REFERENCES cursos(id)', 'PRIMARY KEY (id)'] THEN
    RAISE EXCEPTION 'Constraints incompatíveis com os exercícios';
  END IF;
END $$;
COMMIT;
